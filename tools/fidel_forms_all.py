def FORK(x, y):
    """足先の二股(右向き)。上の先から交点を通って下の先へ。"""
    return f"M{x+50} {y-105} C{x+20} {y-70} {x} {y-35} {x} {y} C{x} {y+40} {x+18} {y+75} {x+42} {y+102}"


def FORKL(x, y):
    """左向きの二股(ያ の左下)。"""
